import { config } from "dotenv";
config({ path: ".env.local" });
import { cert, initializeApp } from "firebase-admin/app";
import { getFirestore } from "firebase-admin/firestore";
import { writeFileSync } from "node:fs";
import type { Tour, BlogPost } from "../../lib/types";
import allPages from "./all-pages.json";

/**
 * Generates the full old-site -> new-site 301 redirect map from the GSC
 * "Top pages" export, per Eran's rules (2026-09):
 *  - /guides/* -> home
 *  - destination/type hub pages -> home, with a country-filter query where
 *    a clean match exists
 *  - everything else with real traffic -> home or the closest equivalent
 *    page (a country match, a migrated blog post, the tours/testimonials
 *    listing) rather than a blanket redirect
 *
 * Output is a static JSON file (lib/data/legacyRedirects.json) rather than
 * a live DB query at build time — it's regenerated by re-running this
 * script, the same way tours.seed.ts is a frozen snapshot rather than a
 * live read.
 *
 * Run with: npx tsx scripts/migrate/generate-redirects.ts
 */

const CLICK_THRESHOLD = 20;

// Old site's /tours-destinations/<continent>/<slug>/ country pages, mapped
// to the exact COUNTRIES enum values so the redirect matches a real filter.
// null = no clean 1:1 country match (a territory, not its own COUNTRIES
