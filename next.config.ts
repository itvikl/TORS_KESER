import type { NextConfig } from "next";
import legacyRedirects from "./lib/data/legacyRedirects.json";

const nextConfig: NextConfig = {
  devIndicators: false,
  experimental: {
    serverActions: {
      // Default is 1MB — too small for the admin tour editor's image
      // uploads (lib/actions/uploads.ts caps individual files at 8MB).
      bodySizeLimit: "10mb",
    },
  },
  images: {
    // Must stay explicit: Firebase App Hosting's Next.js adapter forces
    // `unoptimized: true` whenever this is left undefined
    // (@apphosting/adapter-nextjs overrides.js), which shipped every photo
    // at full size — a ~1.4MB home hero and a 10s mobile LCP in PageSpeed.
    unoptimized: false,
    // Uploads get a fresh UUID path (lib/actions/uploads.ts), so a given URL
    // never changes content — cache the resized copies for 31 days instead
    // of re-encoding them every 4 hours on the single App Hosting instance.
    minimumCacheTTL: 2678400,
    remotePatterns: [
      // Admin-uploaded tour photos (lib/actions/uploads.ts).
      { protocol: "https", hostname: "firebasestorage.googleapis.com", pathname: "/v0/b/**" },
      // Placeholder stock photography used when a tour has no uploaded image yet.
      { protocol: "https", hostname: "lh3.googleusercontent.com", pathname: "/**" },
    ],
  },
  // Old keshertours.com URLs (from the Search Console export) that still
  // carry search traffic — regenerated by scripts/migrate/generate-redirects.ts,
  // not hand-edited. See that script for the targeting rules.
  async redirects() {
    return [
      ...legacyRedirects,
      // Yoast's sitemap URLs from the WordPress site, already known to
      // Search Console — point them at the new sitemap.
      { source: "/sitemap_index.xml", destination: "/sitemap.xml", permanent: true },
      { source: "/:name([a-z0-9_]+-sitemap[0-9]*).xml", destination: "/sitemap.xml", permanent: true },
    ];
  },
  // Baseline hardening for every response. No Content-Security-Policy yet —
  // Stripe Elements and Firebase Auth need a carefully tested allowlist.
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "SAMEORIGIN" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
        ],
      },
    ];
  },
};

export default nextConfig;
